import React, { useState } from 'react';
import { GAME_BLUEPRINTS, synthesizeBlueprintFromPrompt, GameBlueprint } from '../lib/templates';
import { PlayableRobloxGui, RbxFontPreset } from '../components/PlayableRobloxGui';
import { assetUrl, playRbxClick, playStudioSyncChime } from '../lib/sound';
import { triggerFileDownload } from '../lib/rbxlxExporter';
import { useStudio } from '../context/StudioContext';
import {
  Check,
  Copy,
  Download,
  Image as ImageIcon,
  Layers,
  Loader2,
  Sliders,
  Sparkles,
  Wand2,
} from 'lucide-react';

export const GuiForgePage: React.FC = () => {
  const { runExportOrPrankFlow, appendLog } = useStudio();
  const [bp, setBp] = useState<GameBlueprint>(GAME_BLUEPRINTS[1]);
  const [mode, setMode] = useState<'screengui' | 'gfx'>('screengui');
  const [fontPreset, setFontPreset] = useState<RbxFontPreset>('FredokaOne');
  const [cornerRadius, setCornerRadius] = useState<number>(18);
  const [strokeThickness, setStrokeThickness] = useState<number>(3);
  const [customHeader, setCustomHeader] = useState<string>('MYTHIC PET INVENTORY');
  const [guiPrompt, setGuiPrompt] = useState('');
  const [forging, setForging] = useState(false);
  const [copiedLuau, setCopiedLuau] = useState(false);

  const handleForgePrompt = (e: React.FormEvent) => {
    e.preventDefault();
    if (!guiPrompt.trim() || forging) return;
    playRbxClick();
    setForging(true);
    setTimeout(() => {
      const nextBp = synthesizeBlueprintFromPrompt(guiPrompt);
      setBp(nextBp);
      setCustomHeader(nextBp.guiTitle);
      setForging(false);
      playStudioSyncChime();
      appendLog('sync', `[GUI Forge]: Synthesized 9-Slice ScreenGui "${nextBp.guiTitle}"`);
    }, 1850);
  };

  const generatedGuiLuau = `--!strict
-- Generated by Baseplate.gg 9-Slice GUI Forge
local Players = game:GetService("Players")
local TweenService = game:GetService("TweenService")

local screenGui = Instance.new("ScreenGui")
screenGui.Name = "${customHeader.replace(/[^a-zA-Z0-9]/g, '')}Gui"
screenGui.IgnoreGuiInset = true
screenGui.ResetOnSpawn = false

local mainFrame = Instance.new("Frame")
mainFrame.Name = "MainFrame"
mainFrame.AnchorPoint = Vector2.new(0.5, 0.5)
mainFrame.Position = UDim2.fromScale(0.5, 0.5)
mainFrame.Size = UDim2.fromOffset(560, 360)
mainFrame.BackgroundColor3 = Color3.fromRGB(20, 27, 45)
mainFrame.Parent = screenGui

local corner = Instance.new("UICorner")
corner.CornerRadius = UDim.new(0, ${cornerRadius})
corner.Parent = mainFrame

local stroke = Instance.new("UIStroke")
stroke.Thickness = ${strokeThickness}
stroke.Color = Color3.fromRGB(6, 8, 14)
stroke.Parent = mainFrame

local titleLabel = Instance.new("TextLabel")
titleLabel.Size = UDim2.new(1, 0, 0, 54)
titleLabel.BackgroundTransparency = 1
titleLabel.Font = Enum.Font.${fontPreset}
titleLabel.Text = "${customHeader.replace(/"/g, "'")}"
titleLabel.TextSize = 24
titleLabel.TextColor3 = Color3.fromRGB(255, 255, 255)
titleLabel.Parent = mainFrame

screenGui.Parent = Players.LocalPlayer:WaitForChild("PlayerGui")`;

  return (
    <div className="max-w-7xl mx-auto px-4 sm:px-6 py-8 space-y-6">
      {/* Header */}
      <div className="flex flex-col md:flex-row md:items-end justify-between gap-4">
        <div>
          <span className="text-xs font-extrabold uppercase tracking-wider text-[#38BDF8] flex items-center gap-1.5">
            <Layers className="w-4 h-4" /> ForgeGUI-Class Asset Engine • $0 Unlimited
          </span>
          <h1 className="text-3xl sm:text-4xl font-black text-white mt-1">
            9-Slice Roblox GUI &amp; High-CTR GFX Forge
          </h1>
          <p className="text-sm text-slate-400 mt-1">
            Generate playable ScreenGuis with live Roblox Studio Properties (`Enum.Font`, `UICorner`,
            `UIStroke`) or 1920×1080 thumbnails.
          </p>
        </div>

        <div className="flex items-center gap-2 bg-[#111624] border-2 border-[#232D46] p-1.5 rounded-xl self-start">
          <button
            onClick={() => {
              playRbxClick();
              setMode('screengui');
            }}
            className={`px-3.5 py-2 rounded-lg text-xs font-extrabold flex items-center gap-1.5 ${
              mode === 'screengui' ? 'bg-[#00E676] text-[#041A0E]' : 'text-slate-300'
            }`}
          >
            <Sliders className="w-3.5 h-3.5" /> Interactive ScreenGui
          </button>
          <button
            onClick={() => {
              playRbxClick();
              setMode('gfx');
            }}
            className={`px-3.5 py-2 rounded-lg text-xs font-extrabold flex items-center gap-1.5 ${
              mode === 'gfx' ? 'bg-[#38BDF8] text-[#04121F]' : 'text-slate-300'
            }`}
          >
            <ImageIcon className="w-3.5 h-3.5" /> High-CTR GFX Thumbnails
          </button>
        </div>
      </div>

      {/* Prompt Bar */}
      <form
        onSubmit={handleForgePrompt}
        className="rbx-frame rounded-2xl p-3 flex flex-col sm:flex-row items-stretch sm:items-center gap-3"
      >
        <input
          value={guiPrompt}
          onChange={(e) => setGuiPrompt(e.target.value)}
          placeholder="Describe any Roblox shop menu, crate roll HUD, daily spin wheel, or anime aura inventory..."
          className="flex-1 bg-[#0A0E17] border border-[#242F4A] focus:border-[#00E676] rounded-xl px-4 py-3 text-sm text-white placeholder:text-slate-500 outline-none"
        />
        <button
          type="submit"
          disabled={forging}
          className="rbx-btn-green px-6 py-3 rounded-xl text-xs sm:text-sm flex items-center justify-center gap-2 shrink-0"
        >
          {forging ? <Loader2 className="w-4 h-4 animate-spin" /> : <Wand2 className="w-4 h-4" />}
          <span>{forging ? 'Forging UI...' : 'Generate Roblox GUI'}</span>
        </button>
      </form>

      {mode === 'screengui' ? (
        <div className="grid grid-cols-1 lg:grid-cols-12 gap-6">
          {/* Left: Live Interactive ScreenGui Canvas */}
          <div className="lg:col-span-8 space-y-3">
            <div className="flex flex-wrap gap-2">
              {GAME_BLUEPRINTS.map((preset) => (
                <button
                  key={preset.id}
                  onClick={() => {
                    playRbxClick();
                    setBp(preset);
                    setCustomHeader(preset.guiTitle);
                  }}
                  className={`px-3 py-1.5 rounded-xl text-xs font-bold border transition ${
                    bp.id === preset.id
                      ? 'bg-[#00E676]/20 border-[#00E676] text-[#00FF88]'
                      : 'bg-[#111726] border-[#232D46] text-slate-300 hover:text-white'
                  }`}
                >
                  {preset.genre}
                </button>
              ))}
            </div>

            <PlayableRobloxGui
              blueprint={bp}
              fontPreset={fontPreset}
              cornerRadius={cornerRadius}
              strokeThickness={strokeThickness}
              customHeader={customHeader}
            />
          </div>

          {/* Right: Authentic Roblox Studio Properties Window */}
          <div className="lg:col-span-4 rbx-frame rounded-2xl overflow-hidden flex flex-col justify-between">
            <div>
              <div className="px-4 py-3 bg-[#141B2D] border-b border-[#25314E] flex items-center justify-between">
                <span className="text-xs font-black uppercase tracking-wider text-white">
                  Properties — MainFrame
                </span>
                <span className="font-luau text-[10px] text-[#38BDF8]">ScreenGui</span>
              </div>

              <div className="p-4 space-y-4 text-xs">
                {/* Header Text */}
                <div>
                  <label className="block font-luau text-[11px] text-slate-400 mb-1">
                    TextLabel.Text
                  </label>
                  <input
                    value={customHeader}
                    onChange={(e) => setCustomHeader(e.target.value)}
                    className="w-full px-3 py-2 rounded-lg bg-[#0A0E17] border border-[#263250] text-white font-bold"
                  />
                </div>

                {/* Enum.Font */}
                <div>
                  <label className="block font-luau text-[11px] text-slate-400 mb-1">
                    TextLabel.Font (Roblox Enum.Font)
                  </label>
                  <select
                    value={fontPreset}
                    onChange={(e) => {
                      playRbxClick();
                      setFontPreset(e.target.value as RbxFontPreset);
                    }}
                    className="w-full px-3 py-2 rounded-lg bg-[#0A0E17] border border-[#263250] text-white font-luau"
                  >
                    <option value="FredokaOne">Enum.Font.FredokaOne (Simulator)</option>
                    <option value="BuilderSans">Enum.Font.BuilderSans (Modern Roblox)</option>
                    <option value="GothamBlack">Enum.Font.GothamBlack (Bold HUD)</option>
                    <option value="RobotoMono">Enum.Font.RobotoMono (Sci-Fi Tech)</option>
                  </select>
                </div>

                {/* UICorner */}
                <div>
                  <div className="flex justify-between font-luau text-[11px] text-slate-400 mb-1">
                    <span>UICorner.CornerRadius</span>
                    <span className="text-[#00E676]">0, {cornerRadius}</span>
                  </div>
                  <input
                    type="range"
                    min={0}
                    max={28}
                    value={cornerRadius}
                    onChange={(e) => setCornerRadius(Number(e.target.value))}
                    className="w-full accent-[#00E676]"
                  />
                </div>

                {/* UIStroke */}
                <div>
                  <div className="flex justify-between font-luau text-[11px] text-slate-400 mb-1">
                    <span>UIStroke.Thickness</span>
                    <span className="text-[#38BDF8]">{strokeThickness}px</span>
                  </div>
                  <input
                    type="range"
                    min={1}
                    max={6}
                    value={strokeThickness}
                    onChange={(e) => setStrokeThickness(Number(e.target.value))}
                    className="w-full accent-[#38BDF8]"
                  />
                </div>
              </div>
            </div>

            {/* Export Controls */}
            <div className="p-4 bg-[#0B0F1A] border-t border-[#222C45] space-y-2.5">
              <button
                onClick={() => {
                  playRbxClick();
                  navigator.clipboard.writeText(generatedGuiLuau);
                  setCopiedLuau(true);
                  setTimeout(() => setCopiedLuau(false), 1800);
                }}
                className="w-full rbx-btn-dark py-2.5 rounded-xl text-xs flex items-center justify-center gap-2"
              >
                {copiedLuau ? (
                  <Check className="w-4 h-4 text-[#00E676]" />
                ) : (
                  <Copy className="w-4 h-4" />
                )}
                <span>{copiedLuau ? 'Copied ScreenGui Luau!' : 'Copy ScreenGui Luau Builder'}</span>
              </button>

              <button
                onClick={() => {
                  playRbxClick();
                  runExportOrPrankFlow(() => {
                    triggerFileDownload(
                      `${customHeader.replace(/[^a-zA-Z0-9]+/g, '_')}_GUI.luau`,
                      generatedGuiLuau,
                      'text/plain'
                    );
                  });
                }}
                className="w-full rbx-btn-green py-2.5 rounded-xl text-xs flex items-center justify-center gap-2"
              >
                <Download className="w-4 h-4" />
                <span>Sync ScreenGui to StarterGui</span>
              </button>
            </div>
          </div>
        </div>
      ) : (
        /* High-CTR 1920x1080 Roblox GFX Thumbnail Grid */
        <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-6">
          {GAME_BLUEPRINTS.map((item) => (
            <div key={item.id} className="rbx-frame rounded-2xl overflow-hidden flex flex-col">
              <div className="relative h-52 overflow-hidden">
                <img
                  src={assetUrl(item.image)}
                  alt={item.title}
                  className="w-full h-full object-cover hover:scale-105 transition duration-500"
                />
                <span className="absolute top-3 left-3 px-2.5 py-1 rounded-lg bg-[#090D16]/90 border border-white/15 font-luau text-[10px] font-bold text-[#FFD026]">
                  1920×1080 • HIGH-CTR R6 GFX
                </span>
              </div>
              <div className="p-4 flex-1 flex flex-col justify-between space-y-3">
                <div>
                  <h3 className="text-base font-black text-white">{item.title}</h3>
                  <p className="text-xs text-slate-400 mt-1 line-clamp-2">{item.prompt}</p>
                </div>
                <a
                  href={assetUrl(item.image)}
                  download={`${item.id}-thumbnail-1920x1080.jpg`}
                  onClick={() => playRbxClick()}
                  className="rbx-btn-blue py-2 px-4 rounded-xl text-xs flex items-center justify-center gap-1.5"
                >
                  <Sparkles className="w-3.5 h-3.5" />
                  <span>Download 1920×1080 PNG/JPG</span>
                </a>
              </div>
            </div>
          ))}
        </div>
      )}
    </div>
  );
};
